// Helper function: Convert AI workflow format to React Flow format
function convertAIWorkflowToReactFlow(aiWorkflow) {
  const nodes = []
  const edges = []

  // Create nodes for each gesture
  const gestureMappings = aiWorkflow.mappings || []

  gestureMappings.forEach((mapping, index) => {
    const yOffset = index * 150

    // Gesture node
    const gestureNode = {
      id: `gesture-${mapping.gesture_id}-${index}`,
      type: 'gesture',
      position: { x: 100, y: 100 + yOffset },
      data: {
        label: mapping.gesture_id,
        type: 'gesture',
        gesture: mapping.gesture_id
      }
    }

    // Action node
    const actionNode = {
      id: `action-${mapping.action_type}-${mapping.action_id}-${index}`,
      type: mapping.action_type,
      position: { x: 400, y: 100 + yOffset },
      data: {
        label: mapping.action_id,
        type: mapping.action_type,
        action: mapping.action_id,
        reasoning: mapping.reasoning
      }
    }

    // Edge connecting them
    const edge = {
      id: `edge-${index}`,
      source: gestureNode.id,
      target: actionNode.id,
      type: 'smoothstep'
    }

    nodes.push(gestureNode, actionNode)
    edges.push(edge)
  })

  return { nodes, edges }
}

